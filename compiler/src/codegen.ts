// Code generation: s-expressions to AArch64 assembly text.
//
// Ghuloum-style: every expression leaves its value in x0. The output is a
// .S file that includes runtime/asm.h, so the differences between Mach-O
// and ELF stay in one header.
//
// Step 0 (docs/PLAN.md): a program is a sequence of integer literals, and
// its value is the last one's.

import { CompileError } from './errors.ts';
import { posOf, show, type Sexp } from './sexp.ts';

export function compileProgram(forms: Sexp): string {
    if (forms.t === 'nil') throw new CompileError('the program is empty', null);
    const lines = [
        '// generated by slightc -- do not edit',
        '#include "asm.h"',
        '',
        'FUNC slight_main',
        ...compileBody(forms),
        '    ret',
    ];
    return lines.join('\n') + '\n';
}

function compileBody(forms: Sexp): readonly string[] {
    if (forms.t !== 'pair') return [];
    return [...compileExpr(forms.car), ...compileBody(forms.cdr)];
}

function compileExpr(x: Sexp): readonly string[] {
    if (x.t === 'int') return loadWord('x0', x.v << 1n).map((ins, i) => i === 0 ? `${ins}    // ${x.v}` : ins);
    throw new CompileError(`not supported yet: ${show(x)}`, posOf(x));
}

// The shortest movz/movn + movk sequence that puts a 64-bit word in reg:
// start from all zeros (movz) or all ones (movn), whichever leaves fewer
// 16-bit chunks to patch with movk.
export function loadWord(reg: string, word: bigint): readonly string[] {
    const w      = BigInt.asUintN(64, word);
    const chunks = [0, 1, 2, 3].map((k) => ({ k, v: Number((w >> BigInt(16 * k)) & 0xffffn) }));
    const ones   = chunks.filter((c) => c.v === 0xffff).length;
    const zeros  = chunks.filter((c) => c.v === 0).length;
    const fill   = ones > zeros ? 0xffff : 0;
    const [first, ...rest] = chunks.filter((c) => c.v !== fill);
    const hex    = (n: number): string => `#0x${n.toString(16)}`;
    const head   = first === undefined
        ? `    ${fill === 0 ? 'movz' : 'movn'} ${reg}, #0`
        : fill === 0
            ? `    movz ${reg}, ${hex(first.v)}, lsl #${16 * first.k}`
            : `    movn ${reg}, ${hex(~first.v & 0xffff)}, lsl #${16 * first.k}`;
    return [head, ...rest.map((c) => `    movk ${reg}, ${hex(c.v)}, lsl #${16 * c.k}`)];
}
